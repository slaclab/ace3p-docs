#!/usr/bin/env python3
"""Generate input-keyword reference pages from the ACE3P C++ source tree.

ACE3P solvers read input-file keywords through a uniform API::

    Get(kvc, "NumEigenvalues", InitOrFallback<int>(1) or quiet);
    m_kvc.find("EigenSolver.SolverMode", solvermode);

This script scans the source for those calls and emits one Markdown page per
module with keyword, type, default, and the source location that reads it.
The pages are a *starting point* for the reference section: descriptions are
filled in by hand in the narrative docs, but names and defaults always come
from the code so they cannot drift.

Usage:
    python tools/extract_keywords.py /path/to/ace3p [--out docs/reference]
"""
from __future__ import annotations

import argparse
import collections
import os
import re
import subprocess
from datetime import date

MODULES = {
    "omega3p": "Omega3P",
    "emfem": "Shared electromagnetic FEM (emfem)",
    "solver": "Eigensolver and linear-solver options (solver)",
    "s3p": "S3P",
    "tem3p": "TEM3P",
    "gun3p": "Gun3P",
    "kly3p": "Kly3P",
    "multipacting": "Track3P / multipacting",
    "tools": "acdtool",
}

PAT_GET = re.compile(
    r'Get\(\s*([A-Za-z_][\w]*(?:->|\.)?[\w]*)\s*,\s*"([A-Za-z0-9_.]+)"'
    r'(?:\s*,\s*"([A-Za-z0-9_.]+)")?\s*,\s*([^;]*?)\)\s*;',
    re.S,
)
PAT_FIND = re.compile(r'\.find(?:Container)?\(\s*"([A-Za-z0-9_.]+)"')
PAT_DEFAULT = re.compile(
    r'InitOrFallback(?:<\s*([A-Za-z:_<> ]+?)\s*>)?\s*\(\s*'
    r'([^()]*?(?:\([^()]*\))?[^()]*?)\s*\)'
)
PAT_SEV = re.compile(r'\bor\s+(quiet|warn|die)\b')
SEVERITY = {"quiet": "optional", "warn": "optional (warns)", "die": "required"}


def infer_type(explicit: str | None, default: str) -> str:
    if explicit:
        return explicit.replace("std::", "")
    if not default:
        return ""
    if re.fullmatch(r"-?\d+", default):
        return "int"
    if re.fullmatch(r"-?[\d.]+(e[-+]?\d+)?", default):
        return "double"
    if default.startswith('"'):
        return "string"
    return ""


def scan(root: str, module: str):
    rows = {}
    for dp, _, files in os.walk(os.path.join(root, module)):
        for fn in files:
            if not fn.endswith((".C", ".cc", ".cpp", ".h")):
                continue
            path = os.path.join(dp, fn)
            try:
                src = open(path, errors="ignore").read()
            except OSError:
                continue
            rel = os.path.relpath(path, root)
            for m in PAT_GET.finditer(src):
                _, key, alias, spec = m.groups()
                if key.startswith("."):
                    continue
                d = PAT_DEFAULT.search(spec)
                s = PAT_SEV.search(spec)
                default = d.group(2).strip() if d else ""
                typ = infer_type(d.group(1) if d else None, default)
                sev = SEVERITY.get(s.group(1), "") if s else ""
                line = src[: m.start()].count("\n") + 1
                row = dict(key=key, alias=alias or "", type=typ, default=default,
                           presence=sev, loc=f"{rel}:{line}")
                # prefer rows that carry a default over bare find() rows
                if key not in rows or (default and not rows[key]["default"]):
                    rows[key] = row
            for m in PAT_FIND.finditer(src):
                key = m.group(1)
                if key.startswith("."):
                    continue
                line = src[: m.start()].count("\n") + 1
                rows.setdefault(key, dict(key=key, alias="", type="", default="",
                                          presence="", loc=f"{rel}:{line}"))
    return sorted(rows.values(), key=lambda r: r["key"].lower())


def git_describe(root: str) -> str:
    try:
        out = subprocess.run(["git", "-C", root, "log", "-1", "--format=%h %ad", "--date=short"],
                             capture_output=True, text=True, check=True).stdout.strip()
        return out
    except Exception:
        return "unknown"


def render(module: str, title: str, rows, source_rev: str) -> str:
    groups = collections.defaultdict(list)
    for r in rows:
        section = r["key"].rsplit(".", 1)[0] if "." in r["key"] else "(top level)"
        groups[section].append(r)
    out = [
        f"# {title} keyword reference",
        "",
        "!!! info \"Auto-generated\"",
        f"    This page was generated from the ACE3P source tree by `tools/extract_keywords.py` "
        f"on {date.today().isoformat()} (source revision `{source_rev}`). "
        "Keyword names, types, and defaults are taken directly from the code. "
        "Descriptions live in the module user guides. Do not edit this file by hand.",
        "",
        f"**{len(rows)} keywords found.** A blank *Default* means the code reads the keyword "
        "with `find()` and the default is handled elsewhere, or the keyword is a block name.",
        "",
    ]
    for section in sorted(groups, key=lambda s: (s != "(top level)", s.lower())):
        out += [f"## {section}", "", "| Keyword | Type | Default | Presence | Read in |",
                "|---|---|---|---|---|"]
        for r in groups[section]:
            name = r["key"].rsplit(".", 1)[-1] if "." in r["key"] else r["key"]
            alias = f" (alias `{r['alias']}`)" if r["alias"] else ""
            default = f"`{r['default']}`" if r["default"] else ""
            typ = f"`{r['type']}`" if r["type"] else ""
            out.append(f"| `{name}`{alias} | {typ} | {default} | {r['presence']} | `{r['loc']}` |")
        out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("source", help="path to ACE3P source checkout")
    ap.add_argument("--out", default="docs/reference")
    ap.add_argument("--modules", nargs="*", default=["omega3p", "emfem", "solver"])
    args = ap.parse_args()
    rev = git_describe(args.source)
    os.makedirs(args.out, exist_ok=True)
    for mod in args.modules:
        rows = scan(args.source, mod)
        page = render(mod, MODULES.get(mod, mod), rows, rev)
        dest = os.path.join(args.out, f"{mod}.md")
        open(dest, "w").write(page)
        print(f"{dest}: {len(rows)} keywords")


if __name__ == "__main__":
    main()
